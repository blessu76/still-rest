def sitemap_links(pairs, default):
    """<xhtml:link> rows (sitemap.xml) for {lang: url} in the site's language order + x-default."""
    ordered = [(l, pairs[l]) for l in LANGS if l in pairs] + sorted((l, u) for l, u in pairs.items() if l not in LANGS)
    return "".join('    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>\n' % (l, u) for l, u in ordered + [("x-default", default)])


